#!/usr/bin/env bash
# Convert each rules/<name>.md into the target tool's rule format and install it.
# Usage: install-rule.sh <target>... [--workspace DIR]
#   targets: kiro | antigravity | all      (global scope by default)
# Only overwrites installed files carrying the generated-by marker on line 1;
# a hand-written rule of the same name is left alone and reported.
set -euo pipefail
kit=$(cd "$(dirname "$0")/.." && pwd)
marker="# generated by agent_skill_kit"
targets=(); ws=""
while [ $# -gt 0 ]; do
  case $1 in
    --workspace) ws=$2; shift 2 ;;
    kiro|antigravity) targets+=("$1"); shift ;;
    all) targets+=(kiro antigravity); shift ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done
[ ${#targets[@]} -gt 0 ] || { sed -n '2,7p' "$0"; exit 2; }

# read one frontmatter key from a source file
fm() { awk -v k="$2" '/^---/{c++;next} c==1 && $0 ~ "^"k":"{sub("^"k":[ \t]*","");gsub(/^"|"$/,"");print;exit}' "$1"; }
body() { awk '/^---/{c++;next} c>=2' "$1"; }

for t in "${targets[@]}"; do
  case $t in
    kiro)        dest=${ws:+$ws/.kiro/steering};   dest=${dest:-$HOME/.kiro/steering} ;;
    antigravity) dest=${ws:+$ws/.agents/rules};     dest=${dest:-$HOME/.gemini/config/rules} ;;
  esac
  mkdir -p "$dest"
  for src in "$kit"/rules/*.md; do
    n=$(basename "$src" .md); [ "$n" = README ] && continue
    load=$(fm "$src" kit_load); load=${load:-always}
    tgts=$(fm "$src" kit_targets); tgts=${tgts:-all}
    case ",$tgts," in *,all,*|*",$t,"*) ;; *) echo "SKIP $t: $n (kit_targets=$tgts)"; continue ;; esac
    title=$(fm "$src" title); title=${title:-$n}
    desc=$(fm "$src" description); globs=$(fm "$src" globs)
    out="$dest/$n.md"
    if [ -e "$out" ] && [ "$(head -1 "$out")" != "$marker" ]; then echo "SKIP $t: $n (hand-written, not overwriting)"; continue; fi
    case $t in
      kiro)
        case $load in
          always) incl=always ;; glob) incl=fileMatch ;; manual) incl=manual ;;
          model) incl=manual; echo "WARN $n: Kiro has no model_decision; installed as manual" ;;
          *) echo "ERR $n: bad kit_load=$load" >&2; exit 1 ;;
        esac
        { echo "$marker"; echo "---"; echo "title: $title"; echo "inclusion: $incl"
          [ "$incl" = fileMatch ] && echo "fileMatchPattern: $globs"
          echo "---"; body "$src"; } > "$out" ;;
      antigravity)
        case $load in
          always) tr=always_on ;; glob) tr=glob ;; manual) tr=manual ;; model) tr=model_decision ;;
          *) echo "ERR $n: bad kit_load=$load" >&2; exit 1 ;;
        esac
        { echo "$marker"; echo "---"; echo "trigger: $tr"
          [ -n "$desc" ] && echo "description: \"$desc\""
          [ "$tr" = glob ] && echo "globs: \"$globs\""
          echo "---"; body "$src"; } > "$out" ;;
    esac
    echo "OK   $t: $n ($load)"
  done
done
