"""Shared helpers for kit.py. Cross-platform; stdlib only (Python 3.11+ target).

Mirrors scripts/lib/tools.sh: read config/tools.tsv and config/mcp-targets.tsv,
expand ~ per OS, parse kit frontmatter, substitute ${KIT_SECRET:NAME}.
"""
import csv
import os
import re
from pathlib import Path
from typing import Dict, List, Tuple

KIT_MARKER = "generated by agent_skill_kit"


def kit_root() -> Path:
    """Directory holding config/ and scripts/ (this file lives at the root)."""
    return Path(__file__).resolve().parent


def _rows(tsv: Path):
    """Yield non-comment, non-blank rows of a tab-separated file as lists."""
    if not tsv.exists():
        return
    with tsv.open(encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.lstrip().startswith("#"):
                continue
            yield line.split("\t")


def tools_table() -> Dict[str, List[str]]:
    """config/tools.tsv keyed by tool name. Columns match the file header."""
    return {r[0]: r for r in _rows(kit_root() / "config" / "tools.tsv")}


def mcp_table() -> Dict[str, List[str]]:
    """config/mcp-targets.tsv keyed by tool name."""
    return {r[0]: r for r in _rows(kit_root() / "config" / "mcp-targets.tsv")}


def expand(p: str) -> Path:
    """Expand a leading ~ to the OS home. '-' and '' are caller-handled, not here."""
    if p.startswith("~/") or p == "~":
        return Path.home() / p[2:] if len(p) > 2 else Path.home()
    return Path(p)


def resolve_targets(table: dict, want: str) -> List[str]:
    """'all' -> every tool in the table; a name -> [name]; else ValueError."""
    names = list(table.keys())
    if want == "all":
        return names
    if want in table:
        return [want]
    raise ValueError(f"unknown tool: {want} (known: {' '.join(names)})")


# ---- kit frontmatter (rules/<name>.md) --------------------------------------
_FM = re.compile(r"\A---\n(.*?)\n---\n?(.*)\Z", re.S)


def split_frontmatter(text: str) -> Tuple[Dict[str, str], str]:
    """Return (frontmatter dict, body). No frontmatter -> ({}, text)."""
    m = _FM.match(text)
    if not m:
        return {}, text
    fm = {}  # type: Dict[str, str]
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"')
    return fm, m.group(2)


# ---- secrets ----------------------------------------------------------------
_SECRET = re.compile(r"\$\{KIT_SECRET:([A-Za-z0-9_]+)\}")


def load_secrets() -> Dict[str, str]:
    """config/secrets.env as KEY=value. Missing file -> empty dict."""
    f = kit_root() / "config" / "secrets.env"
    out = {}  # type: Dict[str, str]
    if not f.exists():
        return out
    for line in f.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def substitute_secrets(obj, secrets: Dict[str, str]):
    """Recursively replace ${KIT_SECRET:NAME} in str values. Missing key -> KeyError."""
    if isinstance(obj, dict):
        return {k: substitute_secrets(v, secrets) for k, v in obj.items()}
    if isinstance(obj, list):
        return [substitute_secrets(x, secrets) for x in obj]
    if isinstance(obj, str):
        def repl(m):
            name = m.group(1)
            if name not in secrets:
                raise KeyError(name)
            return secrets[name]
        return _SECRET.sub(repl, obj)
    return obj
