"""Shared helpers for kit.py. Cross-platform; stdlib only (Python 3.11+ target).

Reads config/tools.tsv and config/mcp-targets.tsv, expands ~ per OS, parses kit
frontmatter, substitutes ${KIT_SECRET:NAME}.
"""
import csv
import os
import re
from pathlib import Path
from typing import Dict, List, Tuple

KIT_MARKER = "generated by agent_skill_kit"


def kit_root() -> Path:
    """Directory holding config/ and scripts/ (this file lives at the root)."""
    return Path(__file__).resolve().parent


def _rows(tsv: Path):
    """Yield non-comment, non-blank rows of a tab-separated file as lists."""
    if not tsv.exists():
        return
    with tsv.open(encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.lstrip().startswith("#"):
                continue
            yield line.split("\t")


def tools_table() -> Dict[str, List[str]]:
    """config/tools.tsv keyed by tool name. Columns match the file header."""
    return {r[0]: r for r in _rows(kit_root() / "config" / "tools.tsv")}


def mcp_table() -> Dict[str, List[str]]:
    """config/mcp-targets.tsv keyed by tool name."""
    return {r[0]: r for r in _rows(kit_root() / "config" / "mcp-targets.tsv")}


def expand(p: str) -> Path:
    """Expand a leading ~ to the OS home. '-' and '' are caller-handled, not here."""
    if p.startswith("~/") or p == "~":
        return Path.home() / p[2:] if len(p) > 2 else Path.home()
    return Path(p)


def resolve_targets(table: dict, want: str) -> List[str]:
    """'all' -> every tool in the table; a name -> [name]; else ValueError."""
    names = list(table.keys())
    if want == "all":
        return names
    if want in table:
        return [want]
    raise ValueError(f"unknown tool: {want} (known: {' '.join(names)})")


# ---- profiles (selective install) -------------------------------------------
PILOT_ROUTE_START = "<!-- pilot:start -->"
PILOT_ROUTE_END = "<!-- pilot:end -->"


def load_profile(name: str) -> Tuple[List[str], List[str]]:
    """Parse skills/profiles/<name>.txt into (skills, playbook_lines).

    Two sections: '[skills]' (one skill folder name per line, installed to tools)
    and '[playbooks]' (one '<situation> -> <file>.md' line per line, listed in
    pilot's routing table). Lines before any section header, blanks and '#'
    comments are ignored. A missing file is an error the caller reports."""
    f = kit_root() / "skills" / "profiles" / (name + ".txt")
    if not f.is_file():
        raise ValueError("unknown profile: {} (looked for {})".format(name, f))
    skills, playbooks, section = [], [], None
    for raw in f.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1].strip().lower()
            continue
        if section == "skills":
            skills.append(line)
        elif section == "playbooks":
            playbooks.append(line)
    return skills, playbooks


def fill_pilot_routes(skill_md: Path, playbook_lines: List[str]) -> None:
    """Rewrite the pilot:start/end block in a pilot SKILL.md with the given
    routing lines. Idempotent: replaces the block, preserves everything else.
    Each playbook line '<situation> -> <file>.md' becomes '- <situation> -> playbooks/<file>.md'."""
    text = skill_md.read_text(encoding="utf-8")
    if PILOT_ROUTE_START not in text or PILOT_ROUTE_END not in text:
        return  # not a pilot SKILL.md with markers; leave untouched
    rows = []
    for ln in playbook_lines:
        # tolerate both -> and the unicode arrow the table uses
        sep = " -> " if " -> " in ln else ("→" if "→" in ln else None)
        if sep is None:
            continue
        left, right = ln.split(sep, 1)
        fname = right.strip()
        if not fname.startswith("playbooks/"):
            fname = "playbooks/" + fname
        rows.append("- {} → {}".format(left.strip(), fname))
    body = ("\n".join(rows) + "\n") if rows else ""
    pre = text.split(PILOT_ROUTE_START, 1)[0]
    post = text.split(PILOT_ROUTE_END, 1)[1]
    skill_md.write_text(
        pre + PILOT_ROUTE_START + "\n" + body + PILOT_ROUTE_END + post,
        encoding="utf-8")


# ---- kit frontmatter (rules/<name>.md) --------------------------------------
_FM = re.compile(r"\A---\n(.*?)\n---\n?(.*)\Z", re.S)


def split_frontmatter(text: str) -> Tuple[Dict[str, str], str]:
    """Return (frontmatter dict, body). No frontmatter -> ({}, text)."""
    m = _FM.match(text)
    if not m:
        return {}, text
    fm = {}  # type: Dict[str, str]
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"')
    return fm, m.group(2)


# ---- secrets ----------------------------------------------------------------
_SECRET = re.compile(r"\$\{KIT_SECRET:([A-Za-z0-9_]+)\}")


def load_secrets() -> Dict[str, str]:
    """config/secrets.env as KEY=value. Missing file -> empty dict."""
    f = kit_root() / "config" / "secrets.env"
    out = {}  # type: Dict[str, str]
    if not f.exists():
        return out
    for line in f.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def has_secret_ref(obj) -> bool:
    """True if any string value in obj contains a ${KIT_SECRET:NAME} reference."""
    if isinstance(obj, dict):
        return any(has_secret_ref(v) for v in obj.values())
    if isinstance(obj, list):
        return any(has_secret_ref(x) for x in obj)
    if isinstance(obj, str):
        return bool(_SECRET.search(obj))
    return False


def substitute_secrets(obj, secrets: Dict[str, str]):
    """Recursively replace ${KIT_SECRET:NAME} in str values. Missing key -> KeyError."""
    if isinstance(obj, dict):
        return {k: substitute_secrets(v, secrets) for k, v in obj.items()}
    if isinstance(obj, list):
        return [substitute_secrets(x, secrets) for x in obj]
    if isinstance(obj, str):
        def repl(m):
            name = m.group(1)
            if name not in secrets:
                raise KeyError(name)
            return secrets[name]
        return _SECRET.sub(repl, obj)
    return obj


# ---- A-class rule frontmatter converters -----------------------------------
# Each returns the full installed-file text and stamps the kit marker.
# marker_line is kept for call compatibility (callers still pass it); the marker
# text written is KIT_MARKER, now in an HTML comment after the frontmatter.

# Front-matter must be the very first thing in the file or the tool treats the
# whole file as having none (Kiro/Antigravity then default to always-on). So the
# "generated by" marker goes in an HTML comment AFTER the closing ---, never on
# line 1 — same rule fmt_cursor already follows. marker_line is kept for call
# compatibility; the marker text itself is KIT_MARKER.

def fmt_kiro(marker_line, title, load, desc, globs, body):
    incl = {"always": "always", "glob": "fileMatch", "manual": "manual",
            "model": "manual"}[load]
    warn = load == "model"
    out = ["---", "title: " + title, "inclusion: " + incl]
    if incl == "fileMatch":
        out.append("fileMatchPattern: " + globs)
    out.append("---")
    out.append("<!-- " + KIT_MARKER + " -->")
    text = "\n".join(out) + "\n" + body
    return text, (title if warn else None)


def fmt_antigravity(marker_line, title, load, desc, globs, body):
    tr = {"always": "always_on", "glob": "glob", "manual": "manual",
          "model": "model_decision"}[load]
    out = ["---", "trigger: " + tr]
    if desc:
        out.append('description: "' + desc + '"')
    if tr == "glob":
        out.append('globs: "' + globs + '"')
    out.append("---")
    out.append("<!-- " + KIT_MARKER + " -->")
    return "\n".join(out) + "\n" + body, None


def fmt_cursor(marker_line, title, load, desc, globs, body):
    # .mdc must start with the frontmatter ---, so the marker goes in an HTML
    # comment after the closing ---, not on line 1.
    out = ["---"]
    if load == "always":
        out.append("alwaysApply: true")
    elif load == "glob":
        out.append("globs: " + globs)
        if desc:
            out.append("description: " + desc)
    elif load == "model":
        if desc:
            out.append("description: " + desc)
    # manual: all three empty
    out.append("---")
    out.append("<!-- " + KIT_MARKER + " -->")
    return "\n".join(out) + "\n" + body, None


FMT = {"fmt_kiro": fmt_kiro, "fmt_antigravity": fmt_antigravity,
       "fmt_cursor": fmt_cursor}


# ---- B-class single-file merge (CLAUDE.md, AGENTS.md) -----------------------
# Marker text is load-bearing: merge/remove match on it, so changing it would
# orphan blocks already written into users' CLAUDE.md / AGENTS.md. Leave as-is.
KIT_BLOCK_START = ("<!-- kit:start " + KIT_MARKER +
                   " -- do not edit inside; regenerated by install-rule.sh -->")
KIT_BLOCK_END = "<!-- kit:end -->"


def remove_single_file_block(dest: Path) -> bool:
    """Remove the kit block (markers inclusive) from dest, preserving all other
    text. Returns True if a block was found and removed. If removal empties the
    file, the file is deleted. Mirrors merge_single_file's block boundaries."""
    if not dest.exists():
        return False
    text = dest.read_text(encoding="utf-8")
    if KIT_BLOCK_START not in text or KIT_BLOCK_END not in text:
        return False
    pre = text.split(KIT_BLOCK_START, 1)[0]
    post = text.split(KIT_BLOCK_END, 1)[1]
    kept = (pre + post).strip("\n")
    if kept:
        dest.write_text(kept + "\n", encoding="utf-8")
    else:
        dest.unlink()  # file held only the kit block
    return True


def merge_single_file(dest: Path, block: str):
    """Replace the kit block (markers inclusive) in dest with `block`, or append
    it if absent, or create dest from just the block. Preserves all other text.
    `block` is what goes BETWEEN the markers."""
    kept = ""
    if dest.exists():
        text = dest.read_text(encoding="utf-8")
        if KIT_BLOCK_START in text and KIT_BLOCK_END in text:
            pre = text.split(KIT_BLOCK_START, 1)[0]
            post = text.split(KIT_BLOCK_END, 1)[1]
            kept = pre + post
        else:
            kept = text
    # Normalize kept's trailing newlines to exactly one blank line before the
    # block, so repeated reinstalls do not accumulate blank lines.
    parts = []
    if kept.strip():
        parts.append(kept.rstrip("\n") + "\n\n")
    parts.append(KIT_BLOCK_START + "\n")
    parts.append(block)
    parts.append(KIT_BLOCK_END + "\n")
    dest.write_text("".join(parts), encoding="utf-8")


# ---- MCP merge --------------------------------------------------------------
# TOML: read+write via the third-party `toml` package on this 3.6 host; on the
# 3.11 target, read with stdlib tomllib and write with tomli_w/toml. Kept simple:
# use `toml` if importable (covers both until the target is wired up).

def _load_toml(path: Path) -> dict:
    if not path.exists() or path.stat().st_size == 0:
        return {}
    try:
        import tomllib  # 3.11+
        with path.open("rb") as f:
            return tomllib.load(f)
    except ImportError:
        import toml
        return toml.loads(path.read_text(encoding="utf-8"))


def _dump_toml(path: Path, data: dict):
    import toml  # tomllib has no writer; use the package (declared in requirements)
    path.write_text(toml.dumps(data), encoding="utf-8")


def merge_mcp_json(dest: Path, container: str, name: str, server: dict):
    """Set data[container][name] = server in a JSON file, preserving other keys."""
    import json
    data = {}
    if dest.exists() and dest.stat().st_size:
        data = json.loads(dest.read_text(encoding="utf-8"))
    data.setdefault(container, {})[name] = server
    dest.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def merge_mcp_toml(dest: Path, prefix: str, name: str, server: dict):
    """Set data[prefix][name] = server in a TOML file, preserving other keys."""
    data = _load_toml(dest)
    data.setdefault(prefix, {})[name] = server
    _dump_toml(dest, data)


def unmerge_mcp_json(dest: Path, container: str, name: str) -> bool:
    """Remove data[container][name] from a JSON file, preserving other servers.
    Returns True if the server was present. Drops an empty container key."""
    import json
    if not dest.exists() or not dest.stat().st_size:
        return False
    data = json.loads(dest.read_text(encoding="utf-8"))
    servers = data.get(container)
    if not isinstance(servers, dict) or name not in servers:
        return False
    del servers[name]
    if not servers:
        del data[container]
    if not data:
        dest.unlink()  # the file held only kit servers
        return True
    dest.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return True


def unmerge_mcp_toml(dest: Path, prefix: str, name: str) -> bool:
    """Remove data[prefix][name] from a TOML file, preserving other servers.
    Returns True if the server was present. Drops an empty prefix table."""
    data = _load_toml(dest)
    servers = data.get(prefix)
    if not isinstance(servers, dict) or name not in servers:
        return False
    del servers[name]
    if not servers:
        del data[prefix]
    if not data:
        dest.unlink()  # the file held only kit servers
        return True
    _dump_toml(dest, data)
    return True


def list_profiles() -> List[Tuple[str, int, int]]:
    """Every skills/profiles/*.txt as (name, n_skills, n_playbooks), name-sorted."""
    base = kit_root() / "skills" / "profiles"
    out = []
    if base.is_dir():
        for f in sorted(base.glob("*.txt")):
            try:
                sk, pb = load_profile(f.stem)
                out.append((f.stem, len(sk), len(pb)))
            except ValueError:
                out.append((f.stem, 0, 0))
    return out


# ---- GitHub access (anonymous; replaces gh + tar) ---------------------------
_GH = "https://api.github.com"


def _gh_get(url: str, accept="application/vnd.github+json"):
    import urllib.request
    headers = {"Accept": accept, "User-Agent": "agent_skill_kit"}
    # Optional token lifts the 60/hr anonymous rate limit; falls back to anonymous.
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if tok:
        headers["Authorization"] = "Bearer " + tok
    req = urllib.request.Request(url, headers=headers)
    return urllib.request.urlopen(req, timeout=30)


def gh_commit_sha(repo: str, ref: str) -> str:
    """Full commit sha of ref on repo (anonymous API)."""
    import json
    return json.load(_gh_get("{}/repos/{}/commits/{}".format(_GH, repo, ref)))["sha"]


def gh_extract(repo: str, sha: str, dest_dir: Path) -> Path:
    """Download repo@sha tarball and extract into dest_dir. Returns the extracted
    root (the single top-level dir GitHub wraps everything in)."""
    import io, tarfile
    # tarball endpoint 302-redirects to codeload; a github media Accept triggers
    # 415, so send a neutral Accept and let urllib follow the redirect.
    data = _gh_get("{}/repos/{}/tarball/{}".format(_GH, repo, sha),
                   accept="*/*").read()
    tf = tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")
    tf.extractall(dest_dir)
    tf.close()
    roots = [p for p in dest_dir.iterdir() if p.is_dir()]
    return roots[0]  # GitHub wraps in one <owner>-<repo>-<sha> dir


def _gh_tree_entries(repo: str, ref: str) -> list:
    """Recursive tree of repo@ref as full entries (path, type, sha, ...).
    Anonymous API. gh_tree wraps this to return just paths."""
    import json
    d = json.load(_gh_get("{}/repos/{}/git/trees/{}?recursive=1".format(_GH, repo, ref)))
    return d.get("tree", [])


def gh_tree(repo: str, ref: str) -> list:
    """Recursive list of every path in repo@ref (anonymous API)."""
    return [e["path"] for e in _gh_tree_entries(repo, ref)]


def gh_blob_sha(repo: str, ref: str, path: str):
    """The blob sha of one file at repo@ref, or None if absent. Comparing blob
    shas tells if a file changed, independent of the compare API's size limits."""
    import json, urllib.error
    try:
        d = json.load(_gh_get("{}/repos/{}/contents/{}?ref={}".format(_GH, repo, path, ref)))
        return d.get("sha")
    except urllib.error.HTTPError:
        return None
